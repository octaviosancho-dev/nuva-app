#!/usr/bin/env node
/**
 * Builds the SQL that seeds `insights` from `content/insights/*.md`.
 *
 *   node scripts/seed-insights.mjs > seed.sql
 *
 * The markdown is the source of truth for the copy; the table is generated
 * from it, the same way `tokens.ts` is generated from `design/tokens.json`.
 * The SQL upserts on `slug`, so re-running it after an edit updates the rows
 * in place and never duplicates them.
 *
 * Each insight is a `## n · slug` heading, a `**title**` line, then its body.
 * The build fails on anything the InsightCard spec forbids — above all, a body
 * with more than three paragraphs ("if it needs four, it is two insights").
 */
import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'content', 'insights');

/** Interleave order, so the default rotation never serves one category twice in a row. */
const CATEGORIES = ['mood', 'temperature', 'sleep', 'cognitive', 'physical', 'cycle'];
const MAX_PARAGRAPHS = 3;

const fail = (msg) => {
  console.error(`seed-insights: ${msg}`);
  process.exit(1);
};

const byCategory = new Map();

for (const file of readdirSync(dir).filter((f) => f.endsWith('.md')).sort()) {
  const text = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n');
  const category = text.match(/^Category: `([a-z]+)`/m)?.[1];
  if (!category || !CATEGORIES.includes(category)) fail(`${file}: missing or unknown category`);

  const insights = [];
  for (const block of text.split(/^## /m).slice(1)) {
    const [heading, ...rest] = block.split('\n');
    const slug = heading.match(/·\s*([a-z0-9-]+)\s*$/)?.[1];
    const body = rest.join('\n').replace(/\n---\s*$/, '').trim();
    const title = body.match(/^\*\*(.+)\*\*$/m)?.[1];
    if (!slug || !title) fail(`${file}: malformed insight "${heading}"`);

    const paragraphs = body
      .replace(/^\*\*.+\*\*$/m, '')
      .split(/\n{2,}/)
      .map((p) => p.trim())
      .filter(Boolean);
    if (paragraphs.length === 0 || paragraphs.length > MAX_PARAGRAPHS) {
      fail(`${file}: ${slug} has ${paragraphs.length} paragraphs`);
    }
    if (/[!]/.test(title + paragraphs.join(''))) fail(`${file}: ${slug} has an exclamation mark`);
    if (/\.$/.test(title)) fail(`${file}: ${slug} title ends in a full stop`);

    insights.push({ slug, title, body: paragraphs.join('\n\n'), category });
  }
  byCategory.set(category, [...(byCategory.get(category) ?? []), ...insights]);
}

const rows = [];
const longest = Math.max(...[...byCategory.values()].map((l) => l.length));
for (let i = 0; i < longest; i++) {
  for (const category of CATEGORIES) {
    const insight = byCategory.get(category)?.[i];
    if (insight) rows.push({ ...insight, order_index: rows.length + 1 });
  }
}

const slugs = new Set(rows.map((r) => r.slug));
if (slugs.size !== rows.length) fail('duplicate slugs');

/** Dollar-quoted, so apostrophes and dashes in the copy need no escaping. */
const q = (s) => {
  if (s.includes('$c$')) fail('copy contains the quote tag');
  return `$c$${s}$c$`;
};

const values = rows
  .map(
    (r) =>
      `  (${q(r.slug)}, ${q(r.title)}, ${q(r.body)}, '${r.category}', ${r.order_index})`,
  )
  .join(',\n');

process.stdout.write(`-- Generated by scripts/seed-insights.mjs from content/insights. ${rows.length} insights.
insert into public.insights (slug, title, body, category, order_index) values
${values}
on conflict (slug) do update set
  title = excluded.title,
  body = excluded.body,
  category = excluded.category,
  order_index = excluded.order_index;
`);
console.error(
  `seed-insights: ${rows.length} insights — ${CATEGORIES.map((c) => `${c} ${byCategory.get(c)?.length ?? 0}`).join(', ')}`,
);
