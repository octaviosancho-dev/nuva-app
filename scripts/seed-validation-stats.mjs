#!/usr/bin/env node
/**
 * Builds the SQL that seeds `validation_stats` from
 * `content/validation-stats.csv`.
 *
 *   node scripts/seed-validation-stats.mjs > stats.sql
 *   node scripts/seed-validation-stats.mjs path/to/other.csv   (optional path)
 *
 * The CSV has one row per symptom. `lede` and `mechanism` are written; the
 * `percent`, `source` and (optional) `source_url` columns are filled in by hand
 * from a real study. **Only complete rows are seeded** — a row without both a
 * percent and a source is skipped and listed, so nothing unsourced can reach the
 * app. The table enforces the same rule with NOT NULL constraints.
 *
 * Edit the `lede` to match what the source actually measured — the population
 * ("women in early perimenopause", "women aged 40–55") and the timeframe. Do
 * not round a real figure to something rounder.
 *
 * The SQL upserts on `symptom_id`, so re-running after an edit updates rows.
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const text = readFileSync(process.argv[2] ?? join(root, 'content', 'validation-stats.csv'), 'utf8');

/** RFC 4180: quoted fields, doubled quotes, commas and line breaks inside quotes. */
function parseCsv(input) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    if (quoted) {
      if (ch === '"' && input[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && input[i + 1] === '\n') i++;
      row.push(field);
      if (row.some((f) => f !== '')) rows.push(row);
      row = [];
      field = '';
    } else {
      field += ch;
    }
  }
  row.push(field);
  if (row.some((f) => f !== '')) rows.push(row);
  return rows;
}

const [header, ...body] = parseCsv(text);
const col = Object.fromEntries(header.map((h, i) => [h.trim(), i]));
for (const need of ['slug', 'percent', 'lede', 'mechanism', 'source', 'source_url']) {
  if (!(need in col)) {
    console.error(`seed-validation-stats: missing column "${need}"`);
    process.exit(1);
  }
}

const q = (s) => {
  if (s.includes('$v$')) throw new Error('copy contains the quote tag');
  return `$v$${s}$v$`;
};

const ready = [];
const skipped = [];
for (const r of body) {
  const get = (k) => (r[col[k]] ?? '').trim();
  const slug = get('slug');
  const percent = get('percent').replace('%', '');
  const source = get('source');
  if (!percent || !source) {
    skipped.push(slug);
    continue;
  }
  const n = Number(percent);
  if (!Number.isInteger(n) || n < 1 || n > 100) {
    console.error(`seed-validation-stats: ${slug} has percent "${percent}" — a whole number from 1 to 100`);
    process.exit(1);
  }
  if (!get('lede')) {
    console.error(`seed-validation-stats: ${slug} has a figure but no lede`);
    process.exit(1);
  }
  ready.push({ slug, n, lede: get('lede'), mechanism: get('mechanism'), source, url: get('source_url') });
}

if (ready.length === 0) {
  console.error(`seed-validation-stats: no complete rows yet (${skipped.length} waiting on a percent and a source)`);
  process.exit(0);
}

const values = ready
  .map(
    (r) =>
      `  (${q(r.slug)}, ${r.n}, ${q(r.lede)}, ${r.mechanism ? q(r.mechanism) : 'null'}, ${q(r.source)}, ${r.url ? q(r.url) : 'null'})`,
  )
  .join(',\n');

process.stdout.write(`-- Generated by scripts/seed-validation-stats.mjs from content/validation-stats.csv.
insert into public.validation_stats (symptom_id, percent, lede, mechanism, source, source_url)
select s.id, v.percent, v.lede, v.mechanism, v.source, v.source_url
from (values
${values}
) as v(slug, percent, lede, mechanism, source, source_url)
join public.symptoms s on s.slug = v.slug
on conflict (symptom_id) do update set
  percent = excluded.percent,
  lede = excluded.lede,
  mechanism = excluded.mechanism,
  source = excluded.source,
  source_url = excluded.source_url;
`);
console.error(
  `seed-validation-stats: ${ready.length} ready; ${skipped.length} waiting on a percent and a source${skipped.length ? `: ${skipped.join(', ')}` : ''}`,
);
